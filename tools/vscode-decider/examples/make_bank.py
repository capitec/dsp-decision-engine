def tree_doc(name: str, feature: str, splits: list[tuple[str, str, float, int]], outputs: list[dict], default: dict, dtypes: list) -> dict:
    """A small v3 tree: a chain of `feature op threshold` tests, each leading to a leaf or the next test."""
    nodes, edges = [], []
    for i, (nid, op, threshold, leaf) in enumerate(splits):
        nodes.append({"id": nid, "data": {"type": "unary", "condition": {"op": op, "feature": feature if isinstance(feature, str) else feature[i],
                                                                          "threshold": {"param": f"{nid}_threshold", "default": threshold}}}})
        nodes.append({"id": f"{nid}_leaf", "data": {"type": "leaf", "result_idx": leaf}})
        edges.append({"source": nid, "target": f"{nid}_leaf", "data": {"sourceIndex": 0}})
        if i + 1 < len(splits):
            edges.append({"source": nid, "target": splits[i + 1][0], "data": {"sourceIndex": 1}})
    return {"type": "tree", "name": name, "tree": {"nodes": nodes, "edges": edges,
                                                  "output": {"data": outputs, "default": default, "dtypes": dtypes}}}


