"""Generate `bank/`: a credit origination flow at realistic scale, for the extension's tests and demos.

About a thousand steps across a dozen modules: derived features, three
decision trees, and one arm per product (personal loan, credit card,
overdraft, home loan), each with policy rules, pricing from lookup tables,
affordability and limits, then a final decision. Hundreds of params, fourteen
lookup tables and forty applications. Deterministic: rerunning writes the same files.

    uv run python tools/vscode-decider/examples/make_bank.py
"""
