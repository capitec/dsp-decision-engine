def feature(module: str, name: str, args: list[tuple[str, str]], params: list[tuple[str, float]], body: str, ret: str = "float") -> None:
    sig = ", ".join([f"{a}: {t}" for a, t in args] + [f"{p}: float = param({v})" for p, v in params])
    features[module].append(f"def {name}({sig}) -> {ret}:\n    return {body}\n")
    feature_names.append(name)


def module_of(field: str) -> str:
    if field in ("gross_income", "net_income"):
        return "income"
    if field in ("existing_instalments", "card_utilisation", "requested_amount", "collateral_value"):
        return "debt"
    if field in ("months_employed", "months_at_address", "age"):
        return "stability"
    if field in ("missed_payments_12m", "enquiries_6m", "judgements", "bureau_score"):
        return "behaviour"
    return "household"


