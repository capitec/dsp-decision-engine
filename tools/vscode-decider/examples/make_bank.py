def product_files(product: str, p: str, code: int, doc: str) -> tuple[list[str], int]:
    """Write one product's package; return its policy output names and step count."""
    count = 0
    # Policy: the shared rules, then segment overrides for sectors, provinces and channels.
    rules, flags, reasons = [], [], []
    for name, field, op, thr, reason in RULES:
        thr = thr * (1.0 + rnd.choice([-0.1, 0.0, 0.0, 0.1])) if field not in ("age", "judgements") else thr
        fn = f"{p}_{name}"
        rules.append(f'@step(output="{fn}")\ndef {fn}({field}: float, limit: float = param({round(thr, 2)})) -> bool:\n'
                     f'    """{reason}."""\n    return {field} {op} limit\n')
        flags.append(fn)
        reasons.append(reason)
    for seg, field, values in SEGMENT_RULES:
        for v in values:
            key = str(v).lower()
            fn = f"{p}_{seg}_{key}_max_debt"
            vt = "int" if seg == "sector" else "str"
            rules.append(f'@step(output="{fn}")\ndef {fn}({field}: {vt}, debt_service_ratio: float, limit: float = param({round(rnd.uniform(0.3, 0.55), 2)})) -> bool:\n'
                         f'    """Debt repayments too high for {seg} {v}."""\n    return {field} == {v!r} and debt_service_ratio > limit\n')
            flags.append(fn)
            reasons.append(f"Debt repayments too high for {seg} {v}")
            fn2 = f"{p}_{seg}_{key}_min_score"
            rules.append(f'@step(output="{fn2}")\ndef {fn2}({field}: {vt}, bureau_score: float, limit: float = param({float(rnd.choice(range(560, 660, 5)))})) -> bool:\n'
                         f'    """Bureau score too low for {seg} {v}."""\n    return {field} == {v!r} and bureau_score < limit\n')
            flags.append(fn2)
            reasons.append(f"Bureau score too low for {seg} {v}")
            fn3 = f"{p}_{seg}_{key}_min_income"
            rules.append(f'@step(output="{fn3}")\ndef {fn3}({field}: {vt}, net_income: float, limit: float = param({float(rnd.choice(range(3500, 9001, 250)))})) -> bool:\n'
                         f'    """Net income too low for {seg} {v}."""\n    return {field} == {v!r} and net_income < limit\n')
            flags.append(fn3)
            reasons.append(f"Net income too low for {seg} {v}")
            fn4 = f"{p}_{seg}_{key}_max_loan_to_income"
            rules.append(f'@step(output="{fn4}")\ndef {fn4}({field}: {vt}, requested_amount_to_gross_income: float, limit: float = param({round(rnd.uniform(3, 12), 1) if p != "hl" else 60.0})) -> bool:\n'
                         f'    """Loan too large for income in {seg} {v}."""\n    return {field} == {v!r} and requested_amount_to_gross_income > limit\n')
            flags.append(fn4)
            reasons.append(f"Loan too large for income in {seg} {v}")
    count += len(rules)
    agg_args = ",\n    ".join(f"{f}: bool" for f in flags)
    reason_list = ",\n        ".join(f"({f}, {r!r})" for f, r in zip(flags, reasons))
    policy = (HEADER.format(doc=f"{doc} Policy rules: each rule declines an application for one reason.") +
              "from decider import flow, param, step\n\n\n" + "\n\n".join(rules) +
              f'\n\n@step(outputs=("{p}_policy_declined", "{p}_policy_reason"))\ndef {p}_policy_outcome(\n    {agg_args},\n) -> tuple[bool, str]:\n'
              f'    """The first failed rule, in priority order."""\n    for failed, reason in (\n        {reason_list},\n    ):\n'
              f'        if failed:\n            return True, reason\n    return False, ""\n\n\n'
              f'{p}_policy = flow(\n' + "".join(f"    {f},\n" for f in flags) + f'    {p}_policy_outcome,\n    name="policy",\n)\n')
    count += 1
    write(f"products/{product}/policy.py", policy)

    # Pricing: lookup tables, then the rate build-up.
    terms = TERMS[p]
    base_rows = [{"min_term": lo, "max_term": hi, "rate": r} for (lo, hi), r in zip(terms, BASE_RATES[p])]
    loading_rows = [{"grade": g, "loading": round(0.01 * (g - 1) * (1.5 if p != "hl" else 0.5), 4)} for g in range(1, 5)]
    tables = [f"{p}_base_rates", f"{p}_risk_loadings", f"{p}_fees"]
    fee_rows = [{"min_amount": lo, "max_amount": hi, "initiation_fee": fee, "monthly_fee": mf}
                for lo, hi, fee, mf in ([(0, 10000, 165.0, 69.0), (10001, 50000, 690.0, 69.0), (50001, 10_000_000, 1207.5, 69.0)] if p != "hl"
                                        else [(0, 1_000_000, 6037.5, 69.0), (1_000_001, 100_000_000, 6037.5, 69.0)])]
    pricing_steps = []
    pricing = HEADER.format(doc=f"{doc} Pricing: the base rate by term, a loading by risk grade, fees by amount, capped by regulation.")
    pricing += "from decider import dag, flow, param, step\n\nfrom bank.lookup import LookupTable\n\n"
    pricing += (f'{p}_base_rates = LookupTable(\n    name="{p}_base_rates",\n    ranges={{"requested_term": ["min_term", "max_term"]}},\n'
                f'    returns={{"{p}_base_rate": "rate"}},\n    rows={json.dumps(base_rows)},\n)\n'
                f'{p}_risk_loadings = LookupTable(\n    name="{p}_risk_loadings",\n    keys={{"grade": "grade"}},\n'
                f'    returns={{"{p}_risk_loading": "loading"}},\n    rows={json.dumps(loading_rows)},\n)\n'
                f'{p}_fees = LookupTable(\n    name="{p}_fees",\n    ranges={{"requested_amount": ["min_amount", "max_amount"]}},\n'
                f'    returns={{"{p}_initiation_fee": "initiation_fee", "{p}_monthly_fee": "monthly_fee"}},\n    rows={json.dumps(fee_rows)},\n)\n\n\n')
    extra = [
        (f"{p}_salary_discount", "salary_account: bool", "discount: float = param(0.005)", "discount if salary_account else 0.0"),
        (f"{p}_channel_discount", "channel: str", "app_discount: float = param(0.0025)", 'app_discount if channel == "app" else 0.0'),
        (f"{p}_loyalty_discount", "months_at_address: float", "discount: float = param(0.001)", "discount if months_at_address > 60 else 0.0"),
        (f"{p}_clean_record_discount", "clean_record: bool", "discount: float = param(0.002)", "discount if clean_record else 0.0"),
        (f"{p}_fraud_loading", "fraud_referral: bool", "loading: float = param(0.01)", "loading if fraud_referral else 0.0"),
        (f"{p}_collections_loading", "collections_band: int", "per_band: float = param(0.0075)", "per_band * (collections_band - 1)"),
    ]
    for name, arg, par, body in extra:
        pricing_steps.append(name)
        pricing += f"def {name}({arg}, {par}) -> float:\n    return {body}\n\n\n"
    discounts = [e[0] for e in extra[:4]]
    loadings = [e[0] for e in extra[4:]]
    pricing += (f'def {p}_raw_rate({p}_base_rate: float, {p}_risk_loading: float, ' + ", ".join(f"{d}: float" for d in discounts + loadings) +
                f') -> float:\n    return {p}_base_rate + {p}_risk_loading - ' + " - ".join(discounts) + " + " + " + ".join(loadings) + "\n\n\n")
    pricing += (f'@step(output="{p}_rate")\ndef {p}_regulated_rate({p}_raw_rate: float, repo_rate: float = param(0.0775, shared_key="repo_rate"),\n'
                f'                        cap_multiple: float = param({2.2 if p != "hl" else 1.0}), cap_margin: float = param({0.20 if p != "hl" else 0.12})) -> float:\n'
                f'    """The National Credit Act cap: repo times a multiple plus a margin."""\n'
                f'    return min({p}_raw_rate, repo_rate * cap_multiple + cap_margin)\n\n\n')
    pricing += (f'def {p}_monthly_rate({p}_rate: float) -> float:\n    return {p}_rate / 12\n\n\n')
    pricing_steps += [f"{p}_raw_rate", f"{p}_regulated_rate", f"{p}_monthly_rate"]
    pricing += f"{p}_pricing = flow(\n    {p}_base_rates,\n    {p}_risk_loadings,\n    {p}_fees,\n" + "".join(f"    {s},\n" for s in pricing_steps) + '    name="pricing",\n)\n'
    count += 3 + len(pricing_steps)
    write(f"products/{product}/pricing.py", pricing)

    # Affordability: the instalment for the requested amount, a stressed rate, and what fits.
    afford = HEADER.format(doc=f"{doc} Affordability: the instalment at the offered and a stressed rate against disposable income.")
    afford += "from decider import flow, param, step\n\n\n"
    asteps = []

    def a(name, sig, body, ret="float"):
        nonlocal afford
        afford += f"def {name}({sig}) -> {ret}:\n    return {body}\n\n\n"
        asteps.append(name)

    a(f"{p}_instalment", f"requested_amount: float, requested_term: float, {p}_monthly_rate: float, {p}_monthly_fee: float",
      f"requested_amount * {p}_monthly_rate / (1 - (1 + {p}_monthly_rate) ** -requested_term) + {p}_monthly_fee")
    a(f"{p}_stress_rate", f"{p}_rate: float, buffer: float = param({0.02 if p == 'hl' else 0.03})", f"{p}_rate + buffer")
    a(f"{p}_stress_instalment", f"requested_amount: float, requested_term: float, {p}_stress_rate: float",
      f"requested_amount * ({p}_stress_rate / 12) / (1 - (1 + {p}_stress_rate / 12) ** -requested_term)")
    a(f"{p}_affordable_instalment", f"disposable_income_buffered: float, share: float = param({0.35 if p == 'hl' else 0.5})",
      "max(disposable_income_buffered * share, 0.0)")
    a(f"{p}_instalment_fits", f"{p}_stress_instalment: float, {p}_affordable_instalment: float", f"{p}_stress_instalment <= {p}_affordable_instalment", "bool")
    a(f"{p}_max_affordable_amount", f"{p}_affordable_instalment: float, requested_term: float, {p}_stress_rate: float",
      f"{p}_affordable_instalment * (1 - (1 + {p}_stress_rate / 12) ** -requested_term) / ({p}_stress_rate / 12)")
    for i, (lo, hi) in enumerate([(0, 0.2), (0.2, 0.35), (0.35, 0.5), (0.5, 1.0)]):
        a(f"{p}_dti_band_{i}", f"debt_service_ratio: float, lo: float = param({lo}), hi: float = param({hi})", "lo <= debt_service_ratio < hi", "bool")
    for g in range(1, 5):
        a(f"{p}_grade_{g}_share", f"grade: int, share: float = param({round(1.0 - 0.15 * (g - 1), 2)})", f"share if grade == {g} else 0.0")
    a(f"{p}_grade_share", ", ".join(f"{p}_grade_{g}_share: float" for g in range(1, 5)), " + ".join(f"{p}_grade_{g}_share" for g in range(1, 5)))
    afford += f"{p}_affordability = flow(\n" + "".join(f"    {s},\n" for s in asteps) + '    name="affordability",\n)\n'
    count += len(asteps)
    write(f"products/{product}/affordability.py", afford)

    # Limits and the arm's outputs.
    limits = HEADER.format(doc=f"{doc} Limits: product caps and the offer.")
    limits += "from decider import flow, param, step\n\n\n"
    lsteps = []

    def l(name, sig, body, ret="float", output=None):
        nonlocal limits
        deco = f'@step(output="{output}")\n' if output else ""
        limits += f"{deco}def {name}({sig}) -> {ret}:\n    return {body}\n\n\n"
        lsteps.append(name)

    cap = {"pl": 350000.0, "cc": 150000.0, "od": 50000.0, "hl": 5000000.0}[p]
