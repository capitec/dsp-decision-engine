import { describe, it, expect } from 'vitest';
import flatErrors from './fixtures/flat-rule-errors.json';
import treeErrors from './fixtures/tree-errors.json';
import {
  parseFlatRuleValidationErrors,
  groupErrorsByRule,
  hasErrorAtPath,
  getErrorAtPath,
  getSectionErrors as getFlatSectionErrors,
  formatRuleErrors,
} from '../flat-rule-validation-parser';
import {
  parseValidationErrors,
  formatValidationErrors,
  getInvalidNodeIds,
  getInvalidNodeIndices,
  getSectionErrors,
  cleanLoc,
} from '../validation-error-parser';

// Real error lists from decikit's validation_errors, regenerated by fixtures/generate.py.
const flat = flatErrors as Record<string, any[]>;
const tree = treeErrors as Record<string, any[]>;

describe('flat-rule errors from decikit', () => {
  it('a valid document has no errors', () => {
    expect(flat.valid).toEqual([]);
    expect(parseFlatRuleValidationErrors(flat.valid)).toEqual([]);
  });

  it('a node carrying UI-only fields is accepted, but a parameter reference carrying one is rejected on the reference', () => {
    const parsed = parseFlatRuleValidationErrors(flat.ui_only_node_fields);
    expect(parsed).toHaveLength(1);
    expect(parsed[0].ruleIndex).toBe(1);
    expect(parsed[0].conditionPath).toEqual(['rule', 'condition', 'threshold']);
    expect(parsed[0].message).toBe('Extra inputs are not permitted');
  });

  it('an empty composite points at the rule that holds it', () => {
    const [err] = parseFlatRuleValidationErrors(flat.empty_composite);
    expect(err.ruleIndex).toBe(1);
    expect(err.section).toBe('rule');
    expect(err.conditionPath).toEqual(['rule']);
    expect(err.message).toContain('at least one condition');
    expect(formatRuleErrors([err])).toContain('Value error, a composite needs at least one condition');
  });

  it('NOT with two conditions is reported on the composite', () => {
    const [err] = parseFlatRuleValidationErrors(flat.not_with_two_conditions);
    expect(err.ruleIndex).toBe(0);
    expect(err.conditionPath).toEqual(['rule']);
    expect(err.message).toContain('exactly 1 condition');
  });

  it('between without bounds is reported on the condition, not on a bound', () => {
    const [err] = parseFlatRuleValidationErrors(flat.between_without_bounds);
    expect(err.conditionPath).toEqual(['rule', 'condition']);
    expect(err.message).toContain('At least one of min or max');
  });

  it('an empty parameter name collapses its three union branches into the ParamRef cause', () => {
    const parsed = parseFlatRuleValidationErrors(flat.empty_param_name);
    expect(parsed).toHaveLength(1);
    expect(parsed[0].conditionPath).toEqual(['rule', 'condition', 'threshold']);
    expect(parsed[0].message).toContain('no parameter chosen');
    expect(parsed[0].fieldName).toBe('threshold');
  });

  it('an unknown operator is reported on the condition', () => {
    const [err] = parseFlatRuleValidationErrors(flat.bad_op);
    expect(err.conditionPath).toEqual(['rule', 'condition']);
    expect(err.type).toBe('union_tag_invalid');
  });

  it('a bad threshold nested in a composite lands on that condition index', () => {
    const parsed = parseFlatRuleValidationErrors(flat.nested_composite_bad_threshold);
    expect(parsed).toHaveLength(1);
    expect(parsed[0].conditionPath).toEqual(['rule', 'conditions', 1, 'threshold']);
    expect(parsed[0].message).toContain("'1bad'");
    expect(hasErrorAtPath(parsed, ['rule', 'conditions', 1])).toBe(true);
    expect(hasErrorAtPath(parsed, ['rule', 'conditions', 0])).toBe(false);
    expect(getErrorAtPath(parsed, ['rule', 'conditions', 1, 'threshold'])).toContain('1bad');
    expect(formatRuleErrors(parsed)).toMatch(/^• Condition 2 → threshold: .*1bad/);
  });

  it('an out-of-range cases otherwise is reported on the cases node', () => {
    const [err] = parseFlatRuleValidationErrors(flat.cases_otherwise_out_of_range);
    expect(err.ruleIndex).toBe(0);
    expect(err.conditionPath).toEqual(['rule']);
    expect(err.message).toContain('branch index 7 is out of range for 2 branch(es)');
  });

  it('a cases when with no patterns keeps one error: the branch that matches the node op', () => {
    const parsed = parseFlatRuleValidationErrors(flat.cases_when_missing_patterns);
    expect(parsed).toHaveLength(1);
    expect(parsed[0].conditionPath).toEqual(['rule', 'conditions', 0, 'when']);
    expect(parsed[0].message).toBe('Field required');
    expect(formatRuleErrors(parsed)).toBe('• Condition 1 → when: Field required');
  });

  it('a build error has no rule: it is kept with its message and no section', () => {
    const parsed = parseFlatRuleValidationErrors(flat.result_idx_out_of_range);
    expect(parsed).toHaveLength(1);
    expect(parsed[0].type).toBe('build_error');
    expect(parsed[0].ruleIndex).toBeUndefined();
    expect(parsed[0].section).toBeUndefined();
    expect(formatRuleErrors(parsed)).toContain('result_idx 9 is not a row of the output');
  });

  it('parameter, output and input_schema errors set the section flags', () => {
    const params = parseFlatRuleValidationErrors(flat.parameter_not_an_object);
    expect(params[0].section).toBe('parameters');
    expect(params[0].conditionPath).toEqual(['p']);
    expect(getFlatSectionErrors(params)).toEqual({
      hasInputSchemaErrors: false,
      hasOutputErrors: false,
      hasParameterErrors: true,
    });

    const output = parseFlatRuleValidationErrors(flat.output_dtypes_not_a_list);
    expect(output.every(e => e.section === 'output')).toBe(true);
    expect(output[0].fieldName).toBe('Output Schema Types');
    expect(getFlatSectionErrors(output).hasOutputErrors).toBe(true);

    const schema = parseFlatRuleValidationErrors(flat.input_schema_entry_malformed);
    expect(schema.every(e => e.section === 'input_schema')).toBe(true);
    expect(getFlatSectionErrors(schema).hasInputSchemaErrors).toBe(true);
  });

  it('groups errors by rule index and leaves section errors out of the groups', () => {
    const parsed = parseFlatRuleValidationErrors([...flat.empty_composite, ...flat.parameter_not_an_object]);
    expect([...groupErrorsByRule(parsed).keys()]).toEqual([1]);
  });

  it('every error in every case formats to a non-empty line', () => {
    for (const [name, errors] of Object.entries(flat)) {
      const parsed = parseFlatRuleValidationErrors(errors);
      for (const p of parsed) expect(formatRuleErrors([p]), name).toMatch(/^• .+: .+|^• .+/);
      expect(parsed.length === 0, name).toBe(errors.length === 0);
    }
  });
});

describe('tree errors from decikit', () => {
  const nodes = [{ id: 'a' }, { id: 'l0' }, { id: 'l1' }];

  it('a valid document has no errors', () => {
    expect(parseValidationErrors(tree.valid, nodes)).toEqual([]);
  });

  it('an empty composite is reported on the node itself', () => {
    const [err] = parseValidationErrors(tree.empty_composite, nodes);
    expect(err.affectedNodeIndex).toBe(0);
    expect(err.affectedNodeId).toBe('a');
    expect(err.fieldPath).toEqual([]);
  });

  it('NOT with two conditions and between without bounds name their node and field', () => {
    const [not] = parseValidationErrors(tree.not_with_two_conditions, nodes);
    expect(not.affectedNodeId).toBe('a');
    expect(not.fieldPath).toEqual([]);
    const [between] = parseValidationErrors(tree.between_without_bounds, nodes);
    expect(between.fieldPath).toEqual(['condition']);
  });

  it('an empty parameter name keeps only the ParamRef cause on the threshold', () => {
    const parsed = parseValidationErrors(tree.empty_param_name, nodes);
    expect(parsed).toHaveLength(1);
    expect(parsed[0].fieldPath).toEqual(['condition', 'threshold']);
    expect(parsed[0].message).toContain('no parameter chosen');
    expect([...getInvalidNodeIds(parsed)]).toEqual(['a']);
    expect([...getInvalidNodeIndices(parsed)]).toEqual([0]);
  });

  it('an unknown operator is reported on the condition', () => {
    const [err] = parseValidationErrors(tree.bad_op, nodes);
    expect(err.fieldPath).toEqual(['condition']);
  });

  it('a build error names the node whose result_idx is out of range', () => {
    const parsed = parseValidationErrors(tree.result_idx_out_of_range, nodes);
    expect([...getInvalidNodeIds(parsed)]).toEqual(['l0']);
    expect(formatValidationErrors(parsed)).toContain('result_idx 9 is not a row of the output');
  });

  it('a cycle and an unknown child id are document-level errors on no node', () => {
    for (const name of ['cycle', 'unknown_child_id']) {
      const parsed = parseValidationErrors(tree[name], nodes);
      expect(parsed, name).toHaveLength(1);
      expect(parsed[0].affectedNodeId, name).toBeUndefined();
      expect(getInvalidNodeIds(parsed).size, name).toBe(0);
    }
    expect(formatValidationErrors(parseValidationErrors(tree.cycle, nodes))).toContain('form a cycle');
    expect(formatValidationErrors(parseValidationErrors(tree.unknown_child_id, nodes))).toContain("unknown node 'ghost'");
  });

  it('section flags are all false for node-only errors', () => {
    expect(getSectionErrors(parseValidationErrors(tree.empty_composite, nodes))).toEqual({
      hasFeatureErrors: false,
      hasOutputErrors: false,
      hasParameterErrors: false,
      hasSubtreeErrors: false,
    });
  });

  it('an index beyond the node list still gives the index but no id', () => {
    const [err] = parseValidationErrors(tree.empty_composite, []);
    expect(err.affectedNodeIndex).toBe(0);
    expect(err.affectedNodeId).toBeUndefined();
    expect(formatValidationErrors([err])).toContain('Node at index 0');
  });
});

describe('cleanLoc', () => {
  it('drops node and operator tags and cuts at the first union branch', () => {
    expect(cleanLoc(['unary', 'condition', '>', 'threshold', 'ParamRef', 'param'])).toEqual(['condition', 'threshold']);
    expect(cleanLoc(['cases:isin', 'conditions', 0, 'values'])).toEqual(['conditions', 0, 'values']);
  });

  it('drops errors from the condition branches that do not belong to the node op', () => {
    expect(cleanLoc(['cases:ranges', 'conditions', 0, 'when', 'IsInCondition', 'values'])).toBeNull();
    expect(cleanLoc(['cases:ranges', 'conditions', 0, 'when', 'RangeCondition', 'min'])).toEqual(['conditions', 0, 'when']);
  });
});
