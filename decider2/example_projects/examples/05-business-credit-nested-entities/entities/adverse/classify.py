"""Stage 5.5 -- classify ONE adverse event. Event grain.

This is the innermost work and the file to read if you read only one. Every
function here takes one event and returns one value. There is no collection in
this file, no index, no length, no loop. The collection exists in
`pipelines/business_facility.py` as `Each(Event, ...)` and nowhere else.

That is the claim the whole sketch rests on: **logic for one element of a
collection is written exactly as logic for one record, because a grain makes it
one record.**

Worst case this file runs 600 times for one application and 6 700 000 times in
the monthly batch. In batch it is one kernel over a 6.7 M-row frame. In the
realtime path it is one kernel over a capacity-60 array per entity. Same steps,
same numerics, checked by the equivalence ladder (doc 02 s3.1) -- which this
project needs extended to cover the fold, see FRAMEWORK-DEMANDS D06.
"""

