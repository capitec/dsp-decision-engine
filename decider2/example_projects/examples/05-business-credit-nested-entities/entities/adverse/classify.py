# --------------------------------------------------------------------------
# The threshold table: 14 event types x 3 criticality classes x 2 severities.
# s6.2 gives it 84 cells, Policy-owned, quarterly.
#
# Two keys, from two different grains. `event_type_code` is an Event value;
# `criticality_class` is an Entity value, broadcast down. That single fact is
# spec s13 Q3 in its entirety -- "where does the parameterisation of a shared
# capability by its context live?" -- and the answer this sketch gives is: it is
# an ordinary input, broadcast from the parent grain, and the library capability
# takes the thresholds rather than owning the table.
#
# `overlay=` is stack position 1 (s5.10). It is declared on the *table*, not at
# the call site, because s5.5 requires the overlay to be applied before any
# event is classified -- it changes the classification rather than a value
# derived from it. A call-site overlay could not guarantee that ordering.
# --------------------------------------------------------------------------
